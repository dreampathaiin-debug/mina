package com.meenai.mina.core.docs

import com.meenai.mina.core.knowledge.IndexEntry
import com.meenai.mina.core.knowledge.KnowledgeIndex
import java.io.File

/**
 * The changing lists in the README (built-in knowledge, provider presets) are generated from their sources and placed between `<!-- generated:<name>:start -->` and `<!-- generated:<name>:end -->`.
 * The English README.md (the repo home page) and the Simplified Chinese docs/readme/README.zh-CN.md come from the same sources, one in each language; the English version writes the knowledge display names as-is (no separate translations).
 * `./gradlew updateReadme` rewrites both READMEs; core's `ReadmeSectionsTest` keeps them in step with the generated output. The other translations carry no generated sections.
 *
 * The knowledge list uses the same [KnowledgeIndex.build] as the build index, in the index's order. Provider presets live in the app's `ProviderPresets.kt`;
 * core cannot load the Android module's classes, so the source is read here line by line in the shape `ProviderPreset("name", ProviderConfig.Kind.<kind>, "url")`;
 * the app's `ReadmePresetsTest` compares against the real `ProviderPresets.all`, and fails there when this reading falls behind the source.
 */
object ReadmeSections {
    /** The repo home page, in English, also the source text for each translation. */
    const val README = "README.md"
    const val README_ZH = "docs/readme/README.zh-CN.md"
    const val KNOWLEDGE = "knowledge"
    const val PROVIDERS = "providers"
    const val RESOURCES = "core/src/main/resources"
    const val PRESETS_SOURCE = "app/src/main/java/com/meenai/mina/settings/ProviderPresets.kt"
    private const val NOTE = "<!-- this section is generated by ./gradlew updateReadme; do not edit by hand -->"
    private const val NOTE_EN = "<!-- Generated by ./gradlew updateReadme; do not edit by hand -->"

    fun start(name: String) = "<!-- generated:$name:start -->"
    fun end(name: String) = "<!-- generated:$name:end -->"

    /** One preset in the source; [kind] is the `ProviderConfig.Kind` enum name, and an empty [baseUrl] means Custom. */
    data class Preset(val label: String, val kind: String, val baseUrl: String)

    private val PRESET = Regex("""ProviderPreset\(\s*"([^"]+)"\s*,\s*ProviderConfig\.Kind\.(\w+)\s*,\s*"([^"]*)"""")

    fun presets(source: String): List<Preset> =
        PRESET.findAll(source).map { Preset(it.groupValues[1], it.groupValues[2], it.groupValues[3]) }.toList()

    private fun kindName(kind: String) = when (kind) { "OpenAiCompat" -> "OpenAI-compatible"; "OpenAiResponses" -> "OpenAI Responses"; else -> kind }
    private fun kindNameEn(kind: String) = when (kind) { "OpenAiCompat" -> "OpenAI-compatible"; "OpenAiResponses" -> "OpenAI Responses"; else -> kind }

    /** The interface kinds selectable for Custom: those seen in the presets; Responses last, matching the UI order (`ProviderConfig.Kind.withApiKey`). */
    private fun customKinds(presets: List<Preset>) = presets.map { it.kind }.distinct().sortedBy { it == "OpenAiResponses" }

    /** The English spelling of "a, b, c": a, b or c. */
    private fun orList(items: List<String>) =
        if (items.size <= 1) items.joinToString() else items.dropLast(1).joinToString(", ") + " or " + items.last()

    fun knowledge(entries: List<IndexEntry>): String {
        fun names(kind: String) = entries.filter { it.kind == kind }.joinToString("、") { it.display }
        return listOf(
            NOTE,
            "| Category | Built-in |",
            "|---|---|",
            "| **App** | ${names(KnowledgeIndex.APP)} |",
            "| **Sites** | ${names(KnowledgeIndex.SITE)} |",
            "| **Common procedures** (skills) | ${names(KnowledgeIndex.SKILL)} |",
        ).joinToString("\n")
    }

    fun knowledgeEn(entries: List<IndexEntry>): String {
        fun names(kind: String) = entries.filter { it.kind == kind }.joinToString(", ") { it.display }
        return listOf(
            NOTE_EN,
            "| Category | Built in |",
            "|---|---|",
            "| **Apps** | ${names(KnowledgeIndex.APP)} |",
            "| **Websites** | ${names(KnowledgeIndex.SITE)} |",
            "| **How-to skills** | ${names(KnowledgeIndex.SKILL)} |",
        ).joinToString("\n")
    }

    /** In one line: which presets exist (the empty-url Custom one does not count) and which interface kinds Custom can take (see [customKinds]). */
    fun providers(presets: List<Preset>): String {
        val names = presets.filter { it.baseUrl.isNotEmpty() }.joinToString("、") { it.label }
        val kinds = customKinds(presets).joinToString("、") { kindName(it) }
        return listOf(NOTE, "Built-in presets include $names; for other providers pick Custom, and both the $kinds interfaces connect.").joinToString("\n")
    }

    /** The English version of [providers]; the Custom entry's name is written in parentheses exactly as in the source, matching the Chinese UI. */
    fun providersEn(presets: List<Preset>): String {
        val names = presets.filter { it.baseUrl.isNotEmpty() }.joinToString(", ") { it.label }
        val custom = presets.firstOrNull { it.baseUrl.isEmpty() }?.label
        val kinds = orList(customKinds(presets).map { kindNameEn(it) })
        val pick = if (custom == null) "Custom" else "Custom ($custom)"
        return listOf(NOTE_EN, "Presets for $names and more; for any other provider pick $pick, which takes any $kinds endpoint.").joinToString("\n")
    }

    /** What each section under the repo root [root] should hold; with [english] true this is the README.md (English) version, otherwise README.zh-CN.md's. */
    fun sections(root: File, english: Boolean = true): Map<String, String> {
        val index = KnowledgeIndex.build(File(root, RESOURCES))
        check(index.errors.isEmpty()) { "Built-in knowledge validation failed:\n" + index.errors.joinToString("\n") }
        val presets = presets(File(root, PRESETS_SOURCE).readText())
        check(presets.isNotEmpty()) { "No ProviderPreset read from $PRESETS_SOURCE" }
        return if (english) mapOf(KNOWLEDGE to knowledgeEn(index.entries), PROVIDERS to providersEn(presets))
        else mapOf(KNOWLEDGE to knowledge(index.entries), PROVIDERS to providers(presets))
    }

    /** Replace the content between each pair of markers in [readme] with [sections]; a missing or out-of-order marker fails immediately. */
    fun render(readme: String, sections: Map<String, String>): String =
        sections.entries.fold(readme) { text, (name, body) ->
            val s = text.indexOf(start(name))
            val e = text.indexOf(end(name))
            check(s >= 0 && e > s) { "README is missing ${start(name)} ... ${end(name)}" }
            text.substring(0, s + start(name).length) + "\n" + body + "\n" + text.substring(e)
        }

    /** The `updateReadme` entry point: `<repo root>`. */
    @JvmStatic
    fun main(args: Array<String>) {
        val root = File(args[0])
        listOf(README to true, README_ZH to false).forEach { (name, english) ->
            val file = File(root, name)
            val before = file.readText()
            val after = render(before, sections(root, english))
            if (after != before) file.writeText(after)
            println(if (after != before) "$name updated" else "$name needs no update")
        }
    }
}
