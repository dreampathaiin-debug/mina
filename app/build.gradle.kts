// Build number on the About page: the current commit's short hash; with no git (say, building from a source package) it writes dev
val gitHash: String = runCatching {
    providers.exec { commandLine("git", "rev-parse", "--short=7", "HEAD") }.standardOutput.asText.get().trim()
}.getOrNull()?.takeIf { it.isNotEmpty() } ?: "dev"

android {
    namespace = "com.meenai.mina"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.meenai.mina"
        minSdk = 30
        targetSdk = 35
        versionCode = 67
        versionName = "0.1.66"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("String", "GIT_HASH", "\"$gitHash\"")
        // The Beta tag after the version on the About page; set to false for a stable release
        buildConfigField("boolean", "BETA", "true")
    }

    // The sandbox binary ships only as arm64 (jniLibs/arm64-v8a); the APK is not ABI-restricted, so other devices install normally and show "the sandbox is not supported on this device".
    // The sandbox binary must run directly from nativeLibraryDir, so it has to be extracted to disk on install
    packaging { jniLibs { useLegacyPackaging = true } }

    // For release builds (perf, release) also produce a per-architecture variant: besides the universal APK, a smaller one carrying only the arm64-v8a native libs.
    // Both APKs share code, resources, version and signing and differ only in the other ABIs under lib/; each is a complete APK, not a split pair installed together.
    // Outputs: app-universal-<type>.apk and app-arm64-v8a-<type>.apk. The split applies to every build type,
    // so it is enabled only when this build produces perf/release packages; a plain debug build still yields app-debug.apk.
    splits {
        abi {
            isEnable = gradle.startParameter.taskNames.any { Regex("(?i)(perf|release)").containsMatchIn(it) }
            reset()
            include("arm64-v8a")
            isUniversalApk = true
        }
    }
    // The bundled runtime (assets/runtime/rootfs.tar.xz, generated by tools/sandbox/build-runtime.py) is already xz; do not compress it again
    androidResources { noCompress += "xz" }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // The eval task set (eval/tasks at the repo root) is packed into the test build's assets; the on-device eval runner reads its tasks from there
    sourceSets.getByName("androidTest").assets.srcDir(rootProject.file("eval/tasks"))

    signingConfigs {
        // minSdk 30 se AGP v1 (JAR) signing band kar deta hai; kuch devices archive se
        // sirf v1 signatures padh paate hain, isliye update pre-check ke liye v1 on rakho.
        getByName("debug") {
            enableV1Signing = true
            // /tmp wipe hone par Gradle naya debug keystore bana deta hai, jisse release ka
            // cert badal jata hai aur phone pe update install fail ho jata hai.
            // Isliye keystore path workspace me pin kar diya (durable disk).
            storeFile = file("/workspace/.android/debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
    }

    buildTypes {
        // Installed side by side during on-device acceptance, keeping the release build and user data; the default build identity is unchanged.
        if (providers.gradleProperty("devInstall").isPresent) getByName("debug") {
            applicationIdSuffix = ".dev"
            resValue("string", "app_name", "Mina Dev")
        }
        // The fluency-testing package: not debuggable, like the release build (a debug build skips ahead-of-time compilation, runs the UI several times slower, and is not a fair feel test),
        // signed with the local debug key so it installs over the debug build and keeps data; performance tools can sample it. ./gradlew :app:assemblePerf
        create("perf") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            isProfileable = true
            matchingFallbacks += "release"
        }
    }

    buildFeatures {
        compose = true
        aidl = true
        buildConfig = true
    }
}

